import 'dart:async';
import 'dart:typed_data';

/// Parameters for the memory-hard password hash that protects the master key.
///
/// The architecture note fixes the *algorithm* — Argon2id — but not the cost.
/// These defaults follow RFC 9106's second recommended option (t=3, p=4,
/// m=64 MiB) reduced to two lanes, because Argon2id's parallelism parameter
/// must not exceed the cores a phone will actually give a foreground app.
///
/// On the native backend a derivation with these parameters takes tens of
/// milliseconds; on the pure-Dart fallback it is the single most expensive
/// operation in the app. [KeyVault.benchmark] exists so the app can measure the
/// real cost on the device in front of it instead of guessing.
class Argon2Params {
  const Argon2Params({
    this.memoryKib = 64 * 1024,
    this.iterations = 3,
    this.parallelism = 2,
    this.tagLength = 32,
  });

  /// Memory cost in kibibytes.
  final int memoryKib;

  /// Time cost — number of passes over memory.
  final int iterations;

  /// Lanes. Must be a power of two for the pure-Dart path.
  final int parallelism;

  /// Derived key length in bytes.
  final int tagLength;

  /// A deliberately cheap profile, used by unit tests and by the pre-flight
  /// benchmark that calibrates the real parameters on first run.
  static const Argon2Params fast = Argon2Params(
    memoryKib: 1024,
    iterations: 1,
    parallelism: 1,
  );

  /// The interactive-login profile used for the account password.
  static const Argon2Params interactive = Argon2Params();

  /// A heavier profile used when re-wrapping the master key after a password
  /// change, where a few extra seconds are acceptable.
  static const Argon2Params sensitive = Argon2Params(
    memoryKib: 192 * 1024,
    iterations: 4,
    parallelism: 4,
  );

  // ignore: avoid_positional_boolean_parameters
  Argon2Params withTagLength(int length) => Argon2Params(
        memoryKib: memoryKib,
        iterations: iterations,
        parallelism: parallelism,
        tagLength: length,
      );

  Map<String, dynamic> toJson() => <String, dynamic>{
        'm': memoryKib,
        't': iterations,
        'p': parallelism,
        'l': tagLength,
      };

  factory Argon2Params.fromJson(Map<String, dynamic> json) => Argon2Params(
        memoryKib: (json['m'] as num?)?.toInt() ?? 64 * 1024,
        iterations: (json['t'] as num?)?.toInt() ?? 3,
        parallelism: (json['p'] as num?)?.toInt() ?? 2,
        tagLength: (json['l'] as num?)?.toInt() ?? 32,
      );

  @override
  String toString() => 'Argon2id(m=${memoryKib}KiB, t=$iterations, p=$parallelism)';
}

/// A public/private key pair.
///
/// Private keys are always the raw 32-byte seed. Both backends accept a seed,
/// so a key generated by one can be loaded by the other, which matters because
/// the backend is chosen at runtime.
class CryptoKeyPair {
  const CryptoKeyPair({required this.publicKey, required this.privateKey});

  final Uint8List publicKey;
  final Uint8List privateKey;
}

/// The cryptographic primitive set DarkFlow is built on.
///
/// The interface is deliberately narrow: everything the app needs is expressed
/// here, so the implementation can switch between libsodium and pure Dart
/// without touching a single caller. Everything that must be fast is
/// synchronous; only password hashing — which is meant to be slow — and the
/// curve operations, whose pure-Dart implementations are asynchronous, return
/// futures.
///
/// Security properties the app relies on:
///  * [argon2id] — password hardening, resistant to GPU cracking.
///  * [aesGcmEncrypt] — the AEAD the architecture note mandates (AES-256-GCM).
///  * [x25519] and [ed25519Sign] — key agreement and authentication.
///  * [sha256] and [blake2b] — fingerprints and safety numbers.
abstract interface class CryptoEngine {
  /// One-time setup: opening the native library, warming up workers.
  Future<void> initialise();

  /// Releases native resources.
  Future<void> dispose();

  /// A human-readable identifier, e.g. `libsodium 1.0.21` or `pure Dart`.
  /// Shown on the security screen so a user can see what is protecting them.
  String get backendName;

  /// True when the primitives run in constant-time native code.
  bool get isNative;

  /// True when AES-256-GCM is hardware accelerated on this device. When it is
  /// not, the app still uses AES-GCM because the on-disk format depends on it;
  /// the flag exists so the security screen can be honest about it.
  bool get hasAesHardware;

  // ------------------------------------------------------------- primitives

  /// [count] cryptographically secure random bytes.
  Uint8List randomBytes(int count);

  /// Overwrites [bytes] with zeros, best effort.
  void wipe(Uint8List bytes);

  /// Comparison whose running time does not depend on where the first
  /// difference is.
  bool constantTimeEquals(List<int> a, List<int> b);

  Uint8List sha256(List<int> data);

  Uint8List blake2b(List<int> data, {int length = 32});

  /// HMAC-SHA256, the building block for HKDF and for message authentication.
  Uint8List hmacSha256({required Uint8List key, required Uint8List data});

  // ------------------------------------------------------------------- AEAD

  /// AES-256-GCM. [nonce] must be 12 bytes. Returns `ciphertext || tag`.
  Uint8List aesGcmEncrypt({
    required Uint8List key,
    required Uint8List nonce,
    required Uint8List plaintext,
    required Uint8List aad,
  });

  /// AES-256-GCM open. Throws [CryptoFailure] when the tag does not verify.
  Uint8List aesGcmDecrypt({
    required Uint8List key,
    required Uint8List nonce,
    required Uint8List ciphertext,
    required Uint8List aad,
  });

  // ---------------------------------------------------------------- hashing

  /// Argon2id, per RFC 9106. Runs off the UI isolate, because even the native
  /// implementation allocates tens of megabytes.
  Future<Uint8List> argon2id({
    required Uint8List password,
    required Uint8List salt,
    required Argon2Params params,
  });

  // ------------------------------------------------------------ signatures

  /// A fresh Ed25519 key pair from the platform's random source.
  Future<CryptoKeyPair> generateEd25519();

  /// Rebuilds an Ed25519 key pair from a 32-byte seed. This is how an account
  /// is restored from its recovery phrase.
  Future<CryptoKeyPair> ed25519KeyPairFromSeed(Uint8List seed);

  /// The 32-byte Ed25519 public key for [privateKey] (a 32-byte seed).
  Future<Uint8List> ed25519PublicFromPrivate(Uint8List privateKey);

  Future<Uint8List> ed25519Sign({
    required Uint8List privateKey,
    required Uint8List message,
  });

  Future<bool> ed25519Verify({
    required Uint8List publicKey,
    required Uint8List message,
    required Uint8List signature,
  });

  // ---------------------------------------------------------- key agreement

  Future<CryptoKeyPair> generateX25519();

  Future<CryptoKeyPair> x25519KeyPairFromSeed(Uint8List seed);

  Future<Uint8List> x25519PublicFromPrivate(Uint8List privateKey);

  /// The 32-byte X25519 shared secret.
  Future<Uint8List> x25519({
    required Uint8List privateKey,
    required Uint8List publicKey,
  });
}

/// HKDF-SHA256 (RFC 5869), built once on top of the engine's HMAC.
///
/// Every subkey in DarkFlow comes from here, with a distinct `info` string per
/// purpose, so one root secret yields independent keys for the database, the
/// attachment vault, the mesh and the identity store.
abstract final class Hkdf {
  /// Length of the SHA-256 output and of the extracted pseudo-random key.
  static const int hashLength = 32;

  /// Expands [ikm] into [length] bytes.
  ///
  /// An empty [salt] is treated as a string of [hashLength] zero bytes, which
  /// is what RFC 5869 prescribes.
  static Uint8List derive({
    required CryptoEngine engine,
    required Uint8List ikm,
    required Uint8List salt,
    required List<int> info,
    required int length,
  }) {
    if (length <= 0 || length > 255 * hashLength) {
      throw ArgumentError.value(length, 'length', 'HKDF can output 1..8160 bytes');
    }
    final effectiveSalt = salt.isEmpty ? Uint8List(hashLength) : salt;
    final prk = engine.hmacSha256(key: effectiveSalt, data: ikm);

    final blocks = (length + hashLength - 1) ~/ hashLength;
    final output = Uint8List(blocks * hashLength);
    var previous = Uint8List(0);

    for (var i = 0; i < blocks; i++) {
      final input = Uint8List(previous.length + info.length + 1);
      input.setRange(0, previous.length, previous);
      input.setRange(previous.length, previous.length + info.length, info);
      input[input.length - 1] = i + 1;
      previous = engine.hmacSha256(key: prk, data: input);
      output.setRange(i * hashLength, (i + 1) * hashLength, previous);
    }

    engine.wipe(prk);
    return Uint8List.sublistView(output, 0, length);
  }
}

/// Thrown when an AEAD tag does not verify, a signature is invalid, or a key is
/// malformed. Callers must treat this as "the data is not authentic" and must
/// never fall back to using the plaintext.
class CryptoFailure implements Exception {
  const CryptoFailure(this.message, {this.cause});

  final String message;
  final Object? cause;

  @override
  String toString() => 'CryptoFailure: $message${cause == null ? '' : ' ($cause)'}';
}
